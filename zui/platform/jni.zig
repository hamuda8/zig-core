pub const jint = i32;
pub const jlong = i64;
pub const jfloat = f32;
pub const jdouble = f64;
pub const jsize = jint;

pub const jobject = ?*opaque {};
pub const jclass = jobject;
pub const jstring = jobject;
pub const jthrowable = jobject;
pub const jmethodID = ?*opaque {};
